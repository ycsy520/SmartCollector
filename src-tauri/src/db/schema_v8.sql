-- 迁移 user_version 7→8：隐私闸门的"出口确认"落库（审查 P0-1，§2.2）。
-- 一列，只加不改（03 §6 规则）：outbound_ok = 用户是否**明示**允许把这条原文发给外部模型。
--
-- 为什么必须是一列，而不是命令参数里的那个 bool：
-- `retry_fragment` 只把状态复位成 pending，真正把内容发出去的是后台 worker（异步、另一次
-- 调用、另一个线程）。参数活不到出口那一刻——只在入队时检查一次，等于给用户一个点了也没用的
-- 确认框，或者干脆让 worker 无条件拦死、确认变成假出口。授权必须**持久化**，worker 才能在
-- 唯一的出口处认出"这一条用户已经明示过"。
--
-- 默认 0（未授权）是安全侧：老库现有的所有行、以及每一次新的自动重试，都不会因为这条迁移
-- 而突然被外发。它只在用户看过隐私提示并主动确认那一次被置 1。
ALTER TABLE fragment_status ADD COLUMN outbound_ok INTEGER NOT NULL DEFAULT 0;
